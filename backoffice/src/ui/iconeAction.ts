function normaliser(mot: string): string {
  return mot
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

/** Icône associée au libellé, ou aucune (« Ne pas annuler », libellés sans verbe d'action reconnu). */
export function iconeAction(libelle: string): LucideIcon | undefined {
  const mots = normaliser(libelle)
    .split(/[^a-z0-9]+/)
    .filter(Boolean);
  const premier = mots[0];
  if (!premier || premier === "ne") return undefined;
  // « Semaine précédente », « Page suivante » : la direction compte plus que le nom.
  if (mots.includes("precedente") || mots.includes("precedent")) return ChevronLeft;
  if (mots.includes("suivante") || mots.includes("suivant")) return ChevronRight;
  return PAR_VERBE[premier];
}
